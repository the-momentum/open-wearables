#!/usr/bin/env python3
"""Registry and upstream-sync guard for fork-only wearable providers.

frontbacklabs/open-wearables is a fork of the-momentum/open-wearables. A provider the
fork supports but upstream does not is a "fork-only provider". This script keeps the
list of them (fork-providers.json, next to this skill) and checks them against upstream.

  preflight <slug>   Before building: does the fork or upstream already support it? Any
                     upstream PRs, issues or branches in flight?
  register <slug>    After building: record the files the provider owns and how many
                     lines mentioning it each shared file carries beyond upstream's.
  verify             Before and after every upstream merge: are all fork-only providers
                     still intact, and has upstream started supporting any of them?
  unregister <slug>  After adopting upstream's implementation: drop the entry.
  list               Show the registry.

Exit codes: 0 ok · 1 something is missing or wrong · 2 upstream supports the provider
(build nothing / adopt upstream) · 3 (preflight only) the fork already has the provider.

Standard library only; runs on any python3 >= 3.8 from anywhere inside the repo.
"""

from __future__ import annotations

import argparse
import datetime as _dt
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Dict, List, Optional, Tuple

SKILL_DIR = Path(__file__).resolve().parents[1]
REGISTRY_PATH = SKILL_DIR / "fork-providers.json"
UPSTREAM_REPO = "the-momentum/open-wearables"

ENUM_PATH = "backend/app/schemas/enums/provider.py"
FACTORY_PATH = "backend/app/services/providers/factory.py"

# Paths a fork-only provider owns outright. Upstream never has them until it supports
# the provider itself, so an upstream merge cannot conflict on them before that.
CONVENTIONAL_OWNED = (
    "backend/app/services/providers/{slug}/",
    "backend/app/schemas/providers/{slug}/",
    "backend/app/constants/workout_types/{slug}.py",
    "backend/app/constants/series_types/{slug}.py",
    "backend/app/static/provider-icons/{slug}.svg",
    "backend/app/integrations/celery/tasks/{slug}/",
    "backend/tests/providers/{slug}/",
    "docs/providers/{dashed}-api-integration.mdx",
)

# Regenerated by pre-commit hooks; only checked for presence, never for counts.
GENERATED_FILES = frozenset({"docs/openapi.json", "docs/providers/coverage.mdx"})

# Never counted as a provider's footprint: the SOP itself mentions example slugs.
FOOTPRINT_EXCLUDED_PREFIXES = (".agents/", ".claude/")

MAX_SCAN_BYTES = 8 * 1024 * 1024


# --------------------------------------------------------------------------- git helpers


def _git(*args: str, check: bool = True) -> str:
    result = subprocess.run(["git", *args], cwd=REPO_ROOT, capture_output=True, text=True)
    if check and result.returncode != 0:
        raise RuntimeError(f"git {' '.join(args)} failed: {result.stderr.strip()}")
    return result.stdout


def _repo_root() -> Path:
    result = subprocess.run(["git", "rev-parse", "--show-toplevel"], cwd=SKILL_DIR, capture_output=True, text=True)
    if result.returncode != 0:
        sys.exit("fork_providers.py must live inside the open-wearables git checkout")
    return Path(result.stdout.strip())


REPO_ROOT = _repo_root()


def _ref_exists(ref: str) -> bool:
    return (
        subprocess.run(
            ["git", "rev-parse", "--verify", "--quiet", f"{ref}^{{commit}}"],
            cwd=REPO_ROOT,
            capture_output=True,
        ).returncode
        == 0
    )


def _require_ref(ref: str) -> str:
    if not _ref_exists(ref):
        sys.exit(
            f"Ref '{ref}' not found. Add and fetch the upstream remote first:\n"
            f"  git remote add upstream git@github.com:{UPSTREAM_REPO}.git  # if missing\n"
            f"  git fetch upstream"
        )
    sha = _git("rev-parse", "--short", ref).strip()
    date = _git("log", "-1", "--format=%cd", "--date=short", ref).strip()
    return f"{ref} @ {sha} ({date})"


def _show(ref: str, path: str) -> Optional[str]:
    result = subprocess.run(["git", "show", f"{ref}:{path}"], cwd=REPO_ROOT, capture_output=True)
    if result.returncode != 0:
        return None
    return result.stdout.decode("utf-8", errors="ignore")


def _exists_at(ref: str, path: str) -> bool:
    return (
        subprocess.run(["git", "cat-file", "-e", f"{ref}:{path}"], cwd=REPO_ROOT, capture_output=True).returncode == 0
    )


def _tracked_files() -> List[str]:
    # Tracked plus untracked-but-not-ignored, so `register` sees files not yet committed.
    out = _git("ls-files", "--cached", "--others", "--exclude-standard")
    return sorted(set(line for line in out.splitlines() if line))


def _read_worktree(path: str) -> Optional[str]:
    full = REPO_ROOT / path
    if not full.is_file():
        return None
    if full.stat().st_size > MAX_SCAN_BYTES:
        return None
    data = full.read_bytes()
    if b"\0" in data[:8192]:
        return None
    return data.decode("utf-8", errors="ignore")


# ------------------------------------------------------------------------ slug helpers

SLUG_RE = re.compile(r"^[a-z][a-z0-9_]*$")


def _mention_re(name: str) -> "re.Pattern[str]":
    # Letters/digits on either side mean another word (CorosStrategy is not counted,
    # COROS_CLIENT_ID and "coros" are). Underscore counts as a separator on purpose.
    return re.compile(rf"(?<![A-Za-z0-9]){re.escape(name)}(?![A-Za-z0-9])", re.IGNORECASE)


def _count(text: Optional[str], name: str) -> int:
    return len(_mention_re(name).findall(text)) if text else 0


def _enum_members(text: Optional[str]) -> List[Tuple[str, str]]:
    if not text:
        return []
    return re.findall(r'^\s+([A-Z][A-Z0-9_]*)\s*=\s*"([^"]+)"', text, re.MULTILINE)


def _owned_candidates(slug: str) -> List[str]:
    return [p.format(slug=slug, dashed=slug.replace("_", "-")) for p in CONVENTIONAL_OWNED]


def _path_present(path: str) -> bool:
    full = REPO_ROOT / path
    if path.endswith("/"):
        return full.is_dir() and any(full.iterdir())
    return full.is_file()


# --------------------------------------------------------------------- native detection


def _upstream_support(ref: str, names: List[str]) -> Dict[str, object]:
    """How far `ref` supports a provider under any of `names` (slug + aliases).

    native  - ProviderName member with that value AND (a strategy module or a factory case)
    partial - only one of those signals; a human has to look
    absent  - neither. A name in a comment or docstring does not count: upstream has
              mentioned providers it never shipped (e.g. "coros" in user_connection.py).
    """
    members = [(m, v) for m, v in _enum_members(_show(ref, ENUM_PATH)) if v in names]
    strategies = [
        f"backend/app/services/providers/{n}/strategy.py"
        for n in names
        if _exists_at(ref, f"backend/app/services/providers/{n}/strategy.py")
    ]
    factory = _show(ref, FACTORY_PATH) or ""
    factory_cases = [m for m, _ in members if f"ProviderName.{m}" in factory]
    if members and (strategies or factory_cases):
        status = "native"
    elif members or strategies:
        status = "partial"
    else:
        status = "absent"
    return {
        "status": status,
        "enum_members": [f'{m} = "{v}"' for m, v in members],
        "strategies": strategies,
        "factory_cases": [f"ProviderName.{m}" for m in factory_cases],
    }


def _describe_support(support: Dict[str, object]) -> str:
    bits = []
    if support["enum_members"]:
        bits.append("enum " + ", ".join(support["enum_members"]))  # type: ignore[arg-type]
    if support["strategies"]:
        bits.append(", ".join(support["strategies"]))  # type: ignore[arg-type]
    if support["factory_cases"]:
        bits.append("factory " + ", ".join(support["factory_cases"]))  # type: ignore[arg-type]
    return "; ".join(bits) or "no provider registration"


# ------------------------------------------------------------------------ registry I/O


def _load_registry() -> Dict[str, object]:
    if not REGISTRY_PATH.exists():
        return {"providers": []}
    return json.loads(REGISTRY_PATH.read_text())


def _save_registry(registry: Dict[str, object]) -> None:
    providers = sorted(registry.get("providers", []), key=lambda p: p["slug"])  # type: ignore[index]
    registry["providers"] = providers
    REGISTRY_PATH.write_text(json.dumps(registry, indent=2) + "\n")


def _entry(registry: Dict[str, object], slug: str) -> Optional[Dict[str, object]]:
    for p in registry.get("providers", []):  # type: ignore[union-attr]
        if p["slug"] == slug:
            return p
    return None


# --------------------------------------------------------------------------- commands


def cmd_preflight(args: argparse.Namespace) -> int:
    slug = args.slug
    names = [slug, *args.alias]
    ref_label = _require_ref(args.upstream_ref)
    print(f"Preflight for '{slug}' (aliases: {', '.join(args.alias) or 'none'}) against {ref_label}")
    if _ref_exists("origin/main"):
        behind = _git("rev-list", "--count", f"origin/main..{args.upstream_ref}").strip()
        print(f"origin/main is missing {behind} commit(s) from {args.upstream_ref} (an upstream sync is due if large)")
    print()

    problems = 0
    if not SLUG_RE.match(slug):
        print(f"  ! slug '{slug}' must be lowercase snake_case ([a-z][a-z0-9_]*)")
        problems += 1

    fork_members = _enum_members(_read_worktree(ENUM_PATH))
    fork_values = [v for _, v in fork_members if v not in ("unknown", "internal")]
    collisions = [v for v in fork_values if v != slug and (v in slug or slug in v)]
    if collisions:
        # ProviderName.from_source_string() matches by substring, first enum member wins.
        print(f"  ! '{slug}' overlaps existing provider value(s) {collisions}: from_source_string() would")
        print("    attribute sources ambiguously. Pick a slug that is not a substring of, or contained in, another.")
        problems += 1

    registry = _load_registry()
    in_fork = [v for v in fork_values if v in names]
    if in_fork:
        fork_only = _entry(registry, in_fork[0]) is not None
        kind = "a registered fork-only provider" if fork_only else "already shipped by upstream"
        print(f"VERDICT: ALREADY_IN_FORK - ProviderName already has '{in_fork[0]}' ({kind}).")
        if fork_only and _upstream_support(args.upstream_ref, names)["status"] == "native":
            print(f"  {args.upstream_ref} now supports it natively too: upstream wins. Run `verify` and follow")
            print("  references/upstream-sync.md, 'Adoption'.")
            return 2
        print("  Nothing to build in the fork. If Ren cannot use it yet, only the deploy wiring and the")
        print("  Ren-side handoff are left: references/ren-rollout.md.")
        return 3

    support = _upstream_support(args.upstream_ref, names)
    print(f"Upstream ({args.upstream_ref}): {support['status'].upper()} - {_describe_support(support)}")

    branches = [
        b.strip()
        for b in _git("branch", "-r", "--list", "upstream/*").splitlines()
        if any(n.replace("_", "") in b.lower().replace("-", "").replace("_", "") for n in names)
    ]
    print(f"Upstream branches mentioning it: {', '.join(branches) if branches else 'none'}")

    if not args.offline and shutil.which("gh"):
        for kind in ("prs", "issues"):
            for name in dict.fromkeys(names):
                result = subprocess.run(
                    [
                        "gh",
                        "search",
                        kind,
                        "--repo",
                        UPSTREAM_REPO,
                        name,
                        "--limit",
                        "10",
                        "--json",
                        "number,title,state,url",
                    ],
                    capture_output=True,
                    text=True,
                )
                if result.returncode != 0:
                    print(f"  (gh search {kind} failed: {result.stderr.strip()[:200]})")
                    continue
                hits = json.loads(result.stdout or "[]")
                print(f"Upstream {kind} matching '{name}': {len(hits)}")
                for h in hits:
                    flag = "*" if _count(h["title"], name) else " "
                    print(f"  {flag} #{h['number']} [{h['state']}] {h['title']} - {h['url']}")
        print("  (* = provider named in the title; the others only mention it in the body)")
    else:
        print(
            "Upstream PR/issue search skipped (--offline or gh missing): check "
            f"https://github.com/{UPSTREAM_REPO}/pulls?q={slug} by hand."
        )

    print()
    if support["status"] == "native":
        print("VERDICT: UPSTREAM_NATIVE - upstream already supports it but the fork has not synced it yet.")
        print("  Do not build a bespoke integration. Bring upstream's in: run the next upstream sync, or")
        print("  cherry-pick upstream's provider commit(s) onto a branch off main. Then do the deploy wiring")
        print("  and Ren handoff (references/ren-rollout.md).")
        return 2
    if support["status"] == "partial":
        print("VERDICT: UPSTREAM_PARTIAL - upstream has some of the provider but not a registered strategy.")
        print("  Read what upstream has before deciding; ask the user if it is unclear.")
        return 2
    print("VERDICT: NOT_IN_UPSTREAM - build it as a fork-only provider (SKILL.md, phase 1 onward).")
    print("  An open upstream PR listed above is a decision point: see SKILL.md, phase 0.")
    return 1 if problems else 0


def cmd_register(args: argparse.Namespace) -> int:
    slug = args.slug
    if not SLUG_RE.match(slug):
        sys.exit(f"slug '{slug}' must be lowercase snake_case")
    ref_label = _require_ref(args.upstream_ref)

    fork_values = [v for _, v in _enum_members(_read_worktree(ENUM_PATH))]
    if slug not in fork_values:
        sys.exit(f"'{slug}' is not a ProviderName value in {ENUM_PATH}; finish phase 3 before registering.")
    support = _upstream_support(args.upstream_ref, [slug, *args.alias])
    if support["status"] != "absent":
        sys.exit(
            f"{args.upstream_ref} already has '{slug}' ({_describe_support(support)}). "
            "A provider upstream supports is not fork-only; do not register it."
        )

    owned = [p for p in _owned_candidates(slug) if _path_present(p)]
    for extra in args.owned:
        if not _path_present(extra):
            sys.exit(f"--owned path not found (or empty dir): {extra}")
        owned.append(extra)
    owned = sorted(dict.fromkeys(owned))

    footprint: Dict[str, int] = {}
    for path in _tracked_files():
        if path.startswith(FOOTPRINT_EXCLUDED_PREFIXES) or any(
            path == o or (o.endswith("/") and path.startswith(o)) for o in owned
        ):
            continue
        ours = _count(_read_worktree(path), slug)
        if not ours:
            continue
        theirs = _count(_show(args.upstream_ref, path), slug)
        if path in GENERATED_FILES:
            footprint[path] = 1
        elif ours > theirs:
            footprint[path] = ours - theirs

    registry = _load_registry()
    existing = _entry(registry, slug) or {}
    entry = {
        "slug": slug,
        "display_name": args.display_name or existing.get("display_name") or slug.replace("_", " ").title(),
        "aliases": sorted(set(args.alias) | set(existing.get("aliases", []))),  # type: ignore[arg-type]
        "added": existing.get("added") or _dt.date.today().isoformat(),
        "registered_against": ref_label,
        "notes": args.note if args.note is not None else existing.get("notes", ""),
        "owned_paths": owned,
        "footprint": dict(sorted(footprint.items())),
    }
    providers = [p for p in registry.get("providers", []) if p["slug"] != slug]  # type: ignore[union-attr]
    providers.append(entry)
    registry["providers"] = providers
    _save_registry(registry)

    print(f"Registered fork-only provider '{slug}' against {ref_label}")
    print(f"  owned paths ({len(owned)}):")
    for p in owned:
        print(f"    {p}")
    print(f"  shared-file footprint ({len(footprint)} files, lines mentioning '{slug}' beyond upstream's):")
    for p, n in sorted(footprint.items()):
        print(f"    {n:>3}  {p}{'  (generated: presence only)' if p in GENERATED_FILES else ''}")
    missing = [
        p
        for p in ("backend/app/services/providers/{slug}/", "backend/tests/providers/{slug}/")
        if p.format(slug=slug) not in owned
    ]
    if missing:
        print(f"  ! expected but missing: {[m.format(slug=slug) for m in missing]}")
        return 1
    print("Review the entry in fork-providers.json and commit it with the provider.")
    return 0


def cmd_verify(args: argparse.Namespace) -> int:
    ref_label = _require_ref(args.upstream_ref)
    registry = _load_registry()
    providers = registry.get("providers", [])  # type: ignore[assignment]
    if args.slug:
        providers = [p for p in providers if p["slug"] in args.slug]  # type: ignore[union-attr]
    if not providers:
        print(
            f"No fork-only providers registered{' matching ' + str(args.slug) if args.slug else ''}. Nothing to verify."
        )
        return 0

    print(f"Verifying {len(providers)} fork-only provider(s) against {ref_label}\n")  # type: ignore[arg-type]
    worst = 0
    for p in providers:  # type: ignore[union-attr]
        slug = p["slug"]
        support = _upstream_support(args.upstream_ref, [slug, *p.get("aliases", [])])
        if support["status"] == "native":
            print(f"[NATIVE]  {slug}: {args.upstream_ref} now supports it ({_describe_support(support)}).")
            print("          Upstream wins: replace the fork implementation with upstream's -")
            print("          references/upstream-sync.md, 'Adoption'. Footprint checks skipped.\n")
            worst = max(worst, 2)
            continue
        if support["status"] == "partial":
            print(
                f"[PARTIAL] {slug}: {args.upstream_ref} has part of a '{slug}' provider ({_describe_support(support)})."
            )
            print("          Not native yet: keep the fork implementation, but read upstream's change and")
            print("          tell the user (references/upstream-sync.md, 'Partial upstream support').")
            worst = max(worst, 2)

        problems: List[str] = []
        for path in p.get("owned_paths", []):
            if not _path_present(path):
                problems.append(f"owned path missing: {path}")
        for path, expected in p.get("footprint", {}).items():
            current = _read_worktree(path)
            if current is None:
                problems.append(f"{path}: file missing (it carried {expected} '{slug}' line(s))")
                continue
            ours = _count(current, slug)
            if path in GENERATED_FILES:
                if ours < 1:
                    problems.append(f"{path}: no '{slug}' left - regenerate it (pre-commit hooks)")
                continue
            kept = ours - _count(_show(args.upstream_ref, path), slug)
            if kept < expected:
                problems.append(
                    f"{path}: {max(kept, 0)} of {expected} fork line(s) mentioning '{slug}' left - restore them "
                    f"from the fork side (git show {args.fork_ref}:{path} | grep -n -i {slug})"
                )
        if problems:
            print(f"[MISSING] {slug}:")
            for line in problems:
                print(f"          - {line}")
            if support["status"] == "partial":
                print("          (upstream's own new lines for this provider shift these counts; compare by hand)")
            print()
            worst = max(worst, 1)
        elif support["status"] == "absent":
            print(
                f"[OK]      {slug}: {len(p.get('owned_paths', []))} owned paths present, "
                f"{len(p.get('footprint', {}))} shared-file footprints intact, not in upstream."
            )
    print()
    if worst == 0:
        print("All fork-only providers intact.")
    elif worst == 1:
        print("Fix the MISSING items before committing the merge. Fork-only providers win over upstream.")
    else:
        print("Upstream support detected - see the NATIVE/PARTIAL entries above.")
    return worst


def cmd_unregister(args: argparse.Namespace) -> int:
    registry = _load_registry()
    if not _entry(registry, args.slug):
        print(f"'{args.slug}' is not registered.")
        return 1
    registry["providers"] = [p for p in registry["providers"] if p["slug"] != args.slug]  # type: ignore[union-attr]
    _save_registry(registry)
    print(f"Removed '{args.slug}' from {REGISTRY_PATH.relative_to(REPO_ROOT)}.")
    return 0


def cmd_list(_: argparse.Namespace) -> int:
    providers = _load_registry().get("providers", [])
    if not providers:
        print("No fork-only providers registered.")
        return 0
    for p in providers:  # type: ignore[union-attr]
        print(
            f"{p['slug']:<16} {p['display_name']:<20} added {p['added']}  "
            f"{len(p['owned_paths'])} owned paths, {len(p['footprint'])} shared files"
        )
    return 0


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)

    def with_ref(p: argparse.ArgumentParser) -> argparse.ArgumentParser:
        p.add_argument(
            "--upstream-ref", default="upstream/main", help="upstream ref to compare (default upstream/main)"
        )
        return p

    pre = with_ref(sub.add_parser("preflight", help="does anyone already support this provider?"))
    pre.add_argument("slug")
    pre.add_argument("--alias", action="append", default=[], help="other names upstream might use (repeatable)")
    pre.add_argument("--offline", action="store_true", help="skip the GitHub PR/issue search")
    pre.set_defaults(func=cmd_preflight)

    reg = with_ref(sub.add_parser("register", help="record a fork-only provider's owned files and footprint"))
    reg.add_argument("slug")
    reg.add_argument("--display-name", default=None)
    reg.add_argument("--alias", action="append", default=[], help="other names upstream might use (repeatable)")
    reg.add_argument("--owned", action="append", default=[], help="extra owned path (dir paths end with /)")
    reg.add_argument("--note", default=None, help="free-text note stored with the entry")
    reg.set_defaults(func=cmd_register)

    ver = with_ref(sub.add_parser("verify", help="check fork-only providers survive an upstream merge"))
    ver.add_argument("--slug", action="append", default=[], help="only these providers (repeatable)")
    ver.add_argument("--fork-ref", default="origin/main", help="fork ref named in restore hints")
    ver.set_defaults(func=cmd_verify)

    unreg = sub.add_parser("unregister", help="drop a provider after adopting upstream's implementation")
    unreg.add_argument("slug")
    unreg.set_defaults(func=cmd_unregister)

    lst = sub.add_parser("list", help="show registered fork-only providers")
    lst.set_defaults(func=cmd_list)

    args = parser.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
